# Дан некоторый список, например, вот такой:#
# [1, 2, 3, 4, 5, 6]
# Поделите сумму элементов, стоящих на четных позициях, на сумму элементов, стоящих на нечетных позициях.

lst = [1, 2, 3, 4, 5, 6]
lst_1 = []
lst_2 = []

for num in lst:
    if num %2==0:
        lst_1.append(num)
    else:
        lst_2.append(num)

print(sum(lst_1)/sum(lst_2))


