# Напишите программу для подсчета среднего числа всех введенных пользователям чисел.
# Ввод пользователя должен осуществляться с помощью input.
# Если пользователь вводит ноль, то на экран выводится среднее значение. Используйте цикл while для решения данной задачи

n = int(input("Введите число:"))
lst = []
while n!=0:
    lst.append(n)
    n = int(input("Введите ещё одно число:"))
print(lst)
print(sum(lst)//len(lst))

