# Напишите программу для подсчета среднего числа всех введенных пользователям чисел.
# Ввод пользователя должен осуществляться с помощью input.
# Если пользователь вводит ноль, то на экран выводится среднее значение.
# Используйте цикл while для решения данной задачи

print("Введите число:")
x = int(input())
lst = []
count = 0
while x != 0:
    lst.append(x)
    print("введите ещё раз число:")
    x = int(input())
    count+=1
print(sum(lst)/count)

